export const PRESENCE_COLLECTION = "presence";

// ส่งสัญญาณ "ยังอยู่" ทุกกี่มิลลิวินาที (เฉพาะตอนแอปเปิดอยู่หน้าจอ)
//   ยิ่งถี่ = สถานะสดขึ้น แต่ Firestore อ่าน/เขียนเยอะขึ้น (ทุกเครื่องที่เปิดแอปจะได้รับทุกการเปลี่ยนแปลง)
// (เดิม 120000 = 2 นาที → ปรับเป็น 5 นาที: การอ่านเพิ่มตามกำลังสองของจำนวนเครื่องที่เปิดพร้อมกัน
//  = เครื่อง × 30 ครั้ง/ชม. × เครื่อง ดูกราฟ Firestore Usage ที่เคยพีค ~2.4K/ชม. ตอนเปิด 9 เครื่อง)
export const HEARTBEAT_MS = 300000;

// ถ้าเงียบเกินเวลานี้ถือว่าออฟไลน์ (แอปถูกปิด/เน็ตหลุด/แบตหมด ที่ส่ง "ออฟไลน์" ไม่ทัน) ควรเป็น > 2 เท่าของ HEARTBEAT_MS
export const STALE_MS = 780000;   // เดิม 300000 — ต้องมากกว่า 2 เท่าของ HEARTBEAT_MS เสมอ (13 นาที)

// แสดงจุดสถานะบนรูปโปรไฟล์ที่ขนาดตั้งแต่เท่านี้ขึ้นไป (รูปเล็กในบับเบิลแชทจะไม่แสดงเพื่อไม่ให้รก)
export const DOT_MIN_SIZE = 30;

// ฟังเฉพาะสถานะของคนที่ "เพิ่ง active" แทนการฟังสถานะของผู้ใช้ทุกคนที่เคยสมัคร
//   เดิมทุกเครื่องอ่านเอกสารสถานะของทุกคนตอนเปิดแอป (ผู้ใช้ 1,000 คน = 1,000 ครั้งต่อการเปิด) ทั้งที่ใครเงียบเกิน STALE_MS ก็ออฟไลน์อยู่แล้ว
//   ใหม่: ฟังเฉพาะคนที่ส่งสัญญาณภายใน PRESENCE_WINDOW_MS ล่าสุด → จุดเขียว/เทาตรงเดิม 100% · "ออนไลน์ล่าสุด..." ของคนที่เงียบนานดึงทีละคนเฉพาะตอนเปิดดู
