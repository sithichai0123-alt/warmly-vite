//        x,y,z = เลื่อน (1 ≈ ความกว้างโมเดลหนึ่งช่วง ปรับตามขนาดโมเดลให้เอง)
//        rx,ry,rz = หมุน (เรเดียน) · s = ขยาย (คูณ) · o = ความทึบ 0–1
//   cam = กล้อง: dolly (1 = ระยะเดิม, <1 เข้าใกล้) · pan/tilt = เรเดียน · shake = ความแรงการสั่น
//   flash = [เวลา, ความแรง 0–1, สี] แสงวาบ/คลื่นกระแทกบนเลเยอร์ 2 มิติ (ตรงกับจังหวะเสียง)
// การไล่ค่า: "smooth" (ค่าเริ่มต้น นุ่มทั้งสองด้าน) · "out" (พุ่งแล้วเบรก – ใช้ตอนมาถึง/กระแทก)
//            · "in" (เร่งเข้าหา – ใช้ตอนพุ่งเข้าชน) · "lin" (คงที่)

export const OBJ0 = { x: 0, y: 0, z: 0, rx: 0, ry: 0, rz: 0, s: 1, o: 1 };
export const CAM0 = { dolly: 1, pan: 0, tilt: 0, shake: 0 };

const EASE = {
  lin: u => u,
  smooth: u => u * u * (3 - 2 * u),
  out: u => 1 - (1 - u) * (1 - u) * (1 - u),
  in: u => u * u * u,
};

// อ่านค่าของแทร็กหนึ่ง ณ เวลา t (ก่อนคีย์แรก = คีย์แรก, หลังคีย์สุดท้าย = คีย์สุดท้าย)
export function sampleTrack(track, t, base) {
  const out = { ...base };
  if (!track || !track.length) return out;
  if (t <= track[0][0]) return Object.assign(out, track[0][1]);
  const last = track[track.length - 1];
  if (t >= last[0]) return Object.assign(out, last[1]);
  let i = 0;
  while (i < track.length - 1 && track[i + 1][0] <= t) i++;
  const [t0, a] = track[i], [t1, b, ez] = track[i + 1];
  const span = t1 - t0;
  const u = (EASE[ez] || EASE.smooth)(span > 0 ? (t - t0) / span : 1);
  for (const k in out) {
    const va = a[k] == null ? base[k] : a[k], vb = b[k] == null ? base[k] : b[k];
    out[k] = va + (vb - va) * u;
  }
  return out;
}

export function sampleShow(show, t) {
  return { obj: sampleTrack(show.obj, t, OBJ0), cam: sampleTrack(show.cam, t, CAM0) };
}

