// Gift Show — เสียงที่แก้ให้ยาวพอกับภาพ (ทับเฉพาะชิ้นที่เสียงเดิมสั้นกว่าภาพมาก)
// ใช้ตัวช่วยชุดเดียวกับเสียงของขวัญเดิมใน App.jsx จึงดังเท่ากันและปิด/เปิดด้วยสวิตช์เดียวกัน
// ถ้ามีไฟล์ public/sounds/gift-<id>.mp3 ระบบเดิมจะใช้ไฟล์ก่อนเสมอ (ที่นี่ไม่แตะ)

export function makeShowSounds(h) {
  const { tone, noise, bell, nt } = h;
  return {
    // 💎 เพชร: เดิมมีแค่ระฆัง 5 ใบ ~1.0 วิ (ภาพเล่น 4.4 วิ → เงียบ 3.4 วิ)
    // ใหม่ ~2.95 วิ: ระฆังแก้วไล่ขึ้น → เสียงกรีดคมของเหลี่ยมเพชร → แก้วหึ่งเบาๆ → ประกาย 3 จังหวะ → ระฆังใบใหญ่ปิดท้าย
    diamond() {
      [28, 32, 35, 39, 43].forEach((s, i) => bell(nt(s), i * .11, .3, 1.8));          // ระฆังแก้วไล่ขึ้น (ตรงกับตอนเพชรพุ่งเข้ามา)
      bell(nt(47), .5, .34, 2.2);                                                     // ใบใหญ่ตอนลงกลางจอ
      tone(5200, .5, .55, { vol: .09, att: .04, slide: .55 });                        // เสียงกรีดคมของเหลี่ยม
      noise(.5, 1.1, { vol: .07, from: 9500, to: 5200, hp: 4200 });                   // ประกายฟุ้ง
      tone(nt(16), .55, 1.9, { vol: .07, att: .5, vib: [3, 4.5] });                   // แก้วหึ่งเบาๆ คลอตลอด
      tone(nt(23), .6, 1.8, { vol: .05, att: .5, vib: [3, 5.2] });
      [1.2, 1.7, 2.2].forEach((t, i) => { bell(nt(43 + i * 2), t, .18, 1.5); tone(7000 - i * 600, t, .1, { vol: .05 }); }); // ประกายแตก 3 จังหวะ
      bell(nt(40), 2.66, .3, 2.4); bell(nt(47), 2.72, .26, 2.4);                       // ระฆังใบใหญ่ปิดท้าย
      noise(2.66, .9, { vol: .06, from: 9000, to: 4500, hp: 4000 });
    },
  };
}
